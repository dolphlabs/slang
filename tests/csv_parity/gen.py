"""Generates tests/csv_parity/{main.sl,expected.txt}.

Reading: documents written by Python's csv module (several separators and
line endings, seeded random fields full of separators, quotes, CR, LF and
UTF-8) must read back as exactly the rows Python reads.
Writing: csv.format's output must equal a reference of its quoting rule,
which Python's csv reader must read back to the same rows.

    python3 tests/csv_parity/gen.py
"""
import csv
import io
import os
import random

HERE = os.path.dirname(os.path.abspath(__file__))
rnd = random.Random(4180)
ALPH = ['a', 'b', 'Z', ' ', ',', ';', '\t', '"', '\n', '\r\n', 'é', '☃', '1', '.', "'", '=']


def field():
    if rnd.random() < 0.1:
        return ""
    return "".join(rnd.choice(ALPH) for _ in range(rnd.randint(1, 8)))


def lit(b):
    return 'to_str(b"' + "".join("\\x%02x" % c for c in b) + '")'


src = ['// Generated by tests/csv_parity/gen.py -- do not edit.', '',
       'import "csv";', 'import "encoding";', 'import "strings";', '',
       'fn show(r: result[[[str]], str]) {',
       '    guard let rows = r else let e = err_of(r) { println("ERR " + e); return; }',
       '    for row in rows {',
       '        let parts: [str] = [];',
       '        for f in row {',
       '            push(parts, encoding.hex_encode(to_bytes(f)));',
       '        }',
       '        println("row " + strings.join(parts, ","));',
       '    }',
       '    println("end");',
       '}', '']
exp = []


def hexrows(rows):
    out = []
    for row in rows:
        out.append("row " + ",".join(f.encode().hex() for f in row))
    out.append("end")
    return out


for doc in range(40):
    sep = rnd.choice([",", ";", "\t"])
    term = rnd.choice(["\r\n", "\n"])
    width = rnd.randint(1, 6)
    rows = [[field() for _ in range(width)] for _ in range(rnd.randint(1, 8))]
    # a row of one empty field is written as "" so it is not an empty line
    buf = io.StringIO()
    w = csv.writer(buf, delimiter=sep, lineterminator=term, quoting=csv.QUOTE_MINIMAL)
    w.writerows(rows)
    text = buf.getvalue()
    back = list(csv.reader(io.StringIO(text, newline=""), delimiter=sep, strict=True))
    src.append('let o%d = csv.options();' % doc)
    src.append('o%d.sep = %d;' % (doc, ord(sep)))
    src.append('show(csv.parse_with(%s, o%d));' % (lit(text.encode()), doc))
    exp += hexrows(back)


def our_format(rows):
    out = []
    for row in rows:
        parts = []
        for f in row:
            if f == "" and len(row) == 1:
                parts.append('""')
            elif any(c in f for c in ',"\r\n') or f.startswith((" ", "\t")):
                parts.append('"' + f.replace('"', '""') + '"')
            else:
                parts.append(f)
        out.append(",".join(parts) + "\r\n")
    return "".join(out)


for doc in range(20):
    width = rnd.randint(1, 5)
    rows = [[field() for _ in range(width)] for _ in range(rnd.randint(1, 6))]
    want = our_format(rows)
    assert list(csv.reader(io.StringIO(want, newline=""), strict=True)) == rows
    src.append('let w%d: [[str]] = [];' % doc)
    for row in rows:
        src.append('push(w%d, [%s]);' % (doc, ", ".join(lit(f.encode()) for f in row)))
    src.append('println(encoding.hex_encode(to_bytes(csv.format(w%d))));' % doc)
    exp.append(want.encode().hex())

with open(os.path.join(HERE, "main.sl"), "w") as f:
    f.write("\n".join(src) + "\n")
with open(os.path.join(HERE, "expected.txt"), "w") as f:
    f.write("\n".join(exp) + "\n")
print(len(exp), "lines")
