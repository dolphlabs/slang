#!/usr/bin/env python3
"""Generate the straight-line Wide operations of stdlib/decimal/decimal.sl.

    python3 tests/decimal_vectors/gen_wide.py > stdlib/decimal/wide.sl

slang has no fixed-size arrays, so a Wide is a struct of twelve int
fields, and a loop over its limbs has to go through a switch per access.
That cost dominated every operation (an add was ~90 ns). These are the
same operations written out limb by limb: no switch, no loop, and the C
compiler keeps the limbs in registers. Each is also a leaf to the
compiler (no allocation, loop or call; scalar stores through a borrow),
so calls between them carry no safepoint bracket. Knuth's long
division, the one rare path, still uses the switch accessors in
decimal.sl.
"""

N = 12  # limbs in a Wide
B = "1000000000"  # the limb base, written out: a package constant would
                  # keep these functions from being leaves (see below)
C = 5   # limbs in a Decimal's coefficient


def w(i):
    return f"w{i}"


out = []
emit = out.append

emit("// GENERATED by tests/decimal_vectors/gen_wide.py: do not edit; re-run it.")
emit("// Straight-line forms of the Wide operations: see that file for why.")
emit("")

emit("fn w_is_zero(a: &Wide) -> bool {")
emit("    return (" + " | ".join(f"a.{w(i)}" for i in range(N)) + ") == 0;")
emit("}")
emit("")

emit("// Index of the highest nonzero limb, or -1 for zero.")
emit("fn w_top(a: &Wide) -> int {")
for i in range(N - 1, -1, -1):
    emit(f"    if a.{w(i)} != 0 {{ return {i}; }}")
emit("    return -1;")
emit("}")
emit("")

emit("fn w_cmp(a: &Wide, b: &Wide) -> int {")
for i in range(N - 1, -1, -1):
    emit(f"    if a.{w(i)} != b.{w(i)} {{ if a.{w(i)} < b.{w(i)} {{ return -1; }} return 1; }}")
emit("    return 0;")
emit("}")
emit("")

emit("// a += b. The callers keep values well under 10^108.")
emit("fn w_add(a: &mut Wide, b: &Wide) {")
emit("    let c = 0;")
emit("    let s = 0;")
for i in range(N):
    emit(f"    s = a.{w(i)} + b.{w(i)} + c;")
    emit(f"    c = 0;")
    emit(f"    if s >= {B} {{ s -= {B}; c = 1; }}")
    emit(f"    a.{w(i)} = s;")
emit("}")
emit("")

emit("// a -= b, for a >= b.")
emit("fn w_sub(a: &mut Wide, b: &Wide) {")
emit("    let c = 0;")
emit("    let s = 0;")
for i in range(N):
    emit(f"    s = a.{w(i)} - b.{w(i)} - c;")
    emit(f"    c = 0;")
    emit(f"    if s < 0 {{ s += {B}; c = 1; }}")
    emit(f"    a.{w(i)} = s;")
emit("}")
emit("")

emit("// a += v for 0 <= v < 10^9, stopping as soon as the carry dies.")
emit("fn w_add_small(a: &mut Wide, v: int) {")
emit("    let s = a.w0 + v;")
for i in range(N):
    emit(f"    if s < {B} {{ a.{w(i)} = s; return; }}")
    emit(f"    a.{w(i)} = s - {B};")
    if i + 1 < N:
        emit(f"    s = a.{w(i + 1)} + 1;")
emit("}")
emit("")

emit("// a *= m for 0 <= m < 10^9; false if the product passes 12 limbs.")
emit("fn w_mul_small(a: &mut Wide, m: int) -> bool {")
emit("    let c = 0;")
emit("    let p = 0;")
for i in range(N):
    emit(f"    p = a.{w(i)} * m + c;")
    emit(f"    a.{w(i)} = p % {B};")
    emit(f"    c = p / {B};")
emit("    return c == 0;")
emit("}")
emit("")

emit("// a /= m for 0 < m < 9 * 10^9; returns the remainder.")
emit("fn w_div_small(a: &mut Wide, m: int) -> int {")
emit("    let r = 0;")
emit("    let cur = 0;")
# A divide by a variable is a real hardware divide; the high limbs are
# usually zero (and so is the running remainder there), so skip them.
for i in range(N - 1, -1, -1):
    emit(f"    cur = r * {B} + a.{w(i)};")
    emit(f"    if cur != 0 {{ a.{w(i)} = cur / m; r = cur % m; }}")
emit("    return r;")
emit("}")
emit("")

emit("fn w_mod_small(a: &Wide, m: int) -> int {")
emit("    let r = 0;")
emit("    let cur = 0;")
for i in range(N - 1, -1, -1):
    emit(f"    cur = r * {B} + a.{w(i)};")
    emit(f"    if cur != 0 {{ r = cur % m; }}")
emit("    return r;")
emit("}")
emit("")

emit("// a *= 10^9 (one limb up); false if the top limb falls off.")
emit("fn w_shl_limb(a: &mut Wide) -> bool {")
emit(f"    let lost = a.{w(N - 1)};")
for i in range(N - 1, 0, -1):
    emit(f"    a.{w(i)} = a.{w(i - 1)};")
emit("    a.w0 = 0;")
emit("    return lost == 0;")
emit("}")
emit("")

emit("// a /= 10^9 (one limb down); returns the limb dropped.")
emit("fn w_shr_limb(a: &mut Wide) -> int {")
emit("    let lost = a.w0;")
for i in range(0, N - 1):
    emit(f"    a.{w(i)} = a.{w(i + 1)};")
emit(f"    a.{w(N - 1)} = 0;")
emit("    return lost;")
emit("}")
emit("")

emit(f"// The product of the low {C} limbs of a and of b (two coefficients, or a")
emit("// coefficient and an int): schoolbook by columns. A column is at most")
emit(f"// {C} products under 10^18, so it stays under 2^63 before the carry.")
emit("fn w_mul_coef(a: &Wide, b: &Wide) -> Wide {")
emit("    let r = Wide { " + ", ".join(f"{w(i)}: 0" for i in range(N)) + " };")
emit("    let c = 0;")
emit("    let t = 0;")
for k in range(2 * C - 1):
    terms = [f"a.{w(i)} * b.{w(k - i)}" for i in range(C) if 0 <= k - i < C]
    emit(f"    t = c + " + " + ".join(terms) + ";")
    emit(f"    r.{w(k)} = t % {B};")
    emit(f"    c = t / {B};")
emit(f"    r.{w(2 * C - 1)} = c % {B};")
emit(f"    r.{w(2 * C)} = c / {B};")
emit("    return r;")
emit("}")

print("\n".join(out))
