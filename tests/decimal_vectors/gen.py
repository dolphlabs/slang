#!/usr/bin/env python3
"""Generate stdlib/decimal/vectors_test.sl: decimal's arithmetic against an
independent reference.

    python3 tests/decimal_vectors/gen.py > stdlib/decimal/vectors_test.sl

The reference is Python's fractions.Fraction (exact rational arithmetic)
with the rounding rules written out here, not Python's decimal module, so
nothing in it shares an algorithm with stdlib/decimal: a value is the
exact rational, rounding looks at the exact remainder. The seed is fixed,
so the file is reproducible.
"""

import random
from fractions import Fraction

random.seed(20261110)
MAX = 10 ** 38
MODES = ["HalfEven", "HalfUp", "HalfDown", "Down", "Up", "Floor", "Ceiling"]


def rand_dec():
    """A (text, Fraction, scale) with 1..38 digits and scale 0..38."""
    nd = random.choice([1, 2, 3, 5, 9, 10, 17, 18, 19, 20, 27, 36, 37, 38,
                        random.randint(1, 38)])
    coef = random.randint(10 ** (nd - 1) if nd > 1 else 0, 10 ** nd - 1)
    scale = random.choice([0, 1, 2, 4, 8, 9, 10, 18, 19, 30, 38,
                           random.randint(0, 38)])
    neg = random.random() < 0.4 and coef != 0
    return coef, scale, neg


def text(coef, scale, neg):
    s = str(coef).rjust(scale + 1, "0")
    if scale:
        s = s[:-scale] + "." + s[-scale:]
    return ("-" if neg else "") + s


def frac(coef, scale, neg):
    return Fraction(-coef if neg else coef, 10 ** scale)


def round_to(x, scale, mode):
    """x (a Fraction) rounded to `scale` digits: (coef, neg)."""
    neg = x < 0
    m = abs(x) * 10 ** scale
    q = m.numerator // m.denominator
    r = m - q
    if r != 0:
        half = Fraction(1, 2)
        up = {
            "Down": False,
            "Up": True,
            "Floor": neg,
            "Ceiling": not neg,
            "HalfUp": r >= half,
            "HalfDown": r > half,
            "HalfEven": r > half or (r == half and q % 2 == 1),
        }[mode]
        if up:
            q += 1
    return q, neg and q != 0


def exact(x, scale):
    """x as a coefficient at scale, if it is exactly representable."""
    m = x * 10 ** scale
    assert m.denominator == 1
    return abs(m.numerator), m < 0


def out(coef, scale, neg):
    if coef >= MAX:
        return "none"
    return text(coef, scale, neg and coef != 0)


cases = []
for _ in range(400):
    a = rand_dec()
    b = rand_dec()
    fa, fb = frac(*a), frac(*b)
    ta, tb = text(*a), text(*b)
    s = max(a[1], b[1])
    cases.append(("add", ta, tb, 0, "", out(*exact(fa + fb, s)[:1], s, (fa + fb) < 0)))
    cases.append(("sub", ta, tb, 0, "", out(*exact(fa - fb, s)[:1], s, (fa - fb) < 0)))
    ms = a[1] + b[1]
    if ms <= 38:
        c, n = exact(fa * fb, ms)
        cases.append(("mul", ta, tb, 0, "", out(c, ms, n)))
    else:
        cases.append(("mul", ta, tb, 0, "", "none"))
    mode = random.choice(MODES)
    rs = random.randint(0, 38)
    c, n = round_to(fa * fb, rs, mode)
    cases.append(("mul_round", ta, tb, rs, mode, out(c, rs, n)))
    if fb != 0:
        mode = random.choice(MODES)
        ds = random.randint(0, 38)
        c, n = round_to(fa / fb, ds, mode)
        cases.append(("div", ta, tb, ds, mode, out(c, ds, n)))
    mode = random.choice(MODES)
    rs = random.randint(0, 38)
    c, n = round_to(fa, rs, mode)
    cases.append(("round", ta, "", rs, mode, out(c, rs, n)))
    cmp = (fa > fb) - (fa < fb)
    cases.append(("cmp", ta, tb, 0, "", str(cmp)))

# Every mode on the classic halfway and near-halfway values.
for v in ["2.5", "-2.5", "3.5", "-3.5", "2.51", "-2.49", "0.5", "-0.5",
          "1.05", "1.15", "-1.25", "9.995", "0.0049"]:
    c0, s0 = v.replace("-", "").replace(".", ""), len(v.split(".")[1])
    fv = Fraction(v)
    for mode in MODES:
        for rs in [0, 1, 2]:
            if rs < s0:
                c, n = round_to(fv, rs, mode)
                cases.append(("round", v, "", rs, mode, out(c, rs, n)))

print("""// GENERATED by tests/decimal_vectors/gen.py: do not edit; re-run it.
// %d cases of add, sub, mul, mul_round, div, round and cmp, with
// expected results from exact rational arithmetic (Python Fraction) and
// rounding rules written independently of stdlib/decimal.
""" % len(cases))
print("fn vec_cases() -> [[str]] {")
print("    return [")
rows = ['        ["%s", "%s", "%s", "%d", "%s", "%s"]' % c for c in cases]
print(",\n".join(rows))
print("    ];")
print("}")
