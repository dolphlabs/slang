"""Generates tests/text_escape/{main.sl,expected.txt}.

strings.escape_html and strings.escape_js against references written here
from their contracts, and checked independently of both: html.unescape
must give the input back from the HTML form, and json.loads must give the
input back from the JS form (every escape escape_js writes is also a JSON
string escape), so a reference that drifted from correct would fail here
before it could vouch for the runtime.

    python3 tests/text_escape/gen.py
"""
import html
import json
import os
import random

HERE = os.path.dirname(os.path.abspath(__file__))

HTML = {"&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&#34;", "'": "&#39;"}


def ref_html(s):
    return "".join(HTML.get(c, c) for c in s)


def ref_js(s):
    out = []
    for c in s:
        o = ord(c)
        if c in "\n\r\t\b\f\\":
            out.append({"\n": "\\n", "\r": "\\r", "\t": "\\t", "\b": "\\b", "\f": "\\f", "\\": "\\\\"}[c])
        elif o < 0x20 or c in "\"'`$<>&":
            out.append("\\u%04x" % o)
        elif o in (0x2028, 0x2029):
            out.append("\\u%04x" % o)
        else:
            out.append(c)
    return "".join(out)


def lit(s):
    return 'to_str(b"' + "".join("\\x%02x" % b for b in s.encode("utf-8")) + '")'


cases = [
    "",
    "plain text, nothing to do",
    "<script>alert('x')</script>",
    "a & b && c",
    "\"double\" and 'single'",
    "tab\there\nnewline\rcr",
    "back\\slash",
    "`template ${literal}`",
    "</script><!--",
    "café 日本 \U0001f600",
    "line sep para",
    "‧‪ near the separators",
    "\x01\x1f\x7f controls",
    "\b\f",
    "&amp; already escaped",
    "=+/?#%",
]
rnd = random.Random(20261110)
alphabet = "ab<>&\"'`$\\\n\t\x02 é  \U0001f600"
for _ in range(40):
    cases.append("".join(rnd.choice(alphabet) for _ in range(rnd.randint(1, 24))))

src = ['// Generated by tests/text_escape/gen.py -- do not edit.',
       '// strings.escape_html and strings.escape_js; the expected output is',
       '// checked in gen.py against html.unescape and json.loads.',
       '',
       'import "strings";',
       '']
exp = []
for s in cases:
    h, j = ref_html(s), ref_js(s)
    assert html.unescape(h) == s, s
    assert json.loads('"' + j + '"') == s, s
    for bad in "<>\"'":
        assert bad not in h and bad not in j.replace("\\u", "")
    src.append('println(strings.escape_html(%s));' % lit(s))
    src.append('println(strings.escape_js(%s));' % lit(s))
    exp.append(h)
    exp.append(j)
# nothing to escape: the same string back (no copy, but equal either way)
src.append('let same = "nothing to escape here";')
src.append('println(strings.escape_html(same) == same && strings.escape_js(same) == same);')
exp.append("true")

with open(os.path.join(HERE, "main.sl"), "w", encoding="utf-8") as f:
    f.write("\n".join(src) + "\n")
with open(os.path.join(HERE, "expected.txt"), "w", encoding="utf-8") as f:
    f.write("\n".join(exp) + "\n")
print("cases:", len(cases))
