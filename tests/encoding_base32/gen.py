"""Generates tests/encoding_base32/{main.sl,expected.txt}.

base32 and base32hex are checked against Python's base64 module (RFC 4648
section 10's vectors and seeded random inputs); Crockford's base32 against
a reference written here from crockford.com/base32.html, checked by round
trip through Python's integers.

    python3 tests/encoding_base32/gen.py
"""
import base64
import os
import random

HERE = os.path.dirname(os.path.abspath(__file__))
CROCK = "0123456789ABCDEFGHJKMNPQRSTVWXYZ"


def crock_enc(b):
    bits = "".join("{:08b}".format(x) for x in b)
    bits += "0" * (-len(bits) % 5)
    return "".join(CROCK[int(bits[i:i + 5], 2)] for i in range(0, len(bits), 5))


def lit(b):
    return 'b"' + "".join("\\x%02x" % c for c in b) + '"'


def slit(s):
    return 'to_str(' + lit(s.encode()) + ')'


rnd = random.Random(4648)
inputs = [b"", b"f", b"fo", b"foo", b"foob", b"fooba", b"foobar", b"\x00", b"\xff" * 7]
inputs += [bytes(rnd.randrange(256) for _ in range(rnd.randint(1, 40))) for _ in range(40)]

src = ['// Generated by tests/encoding_base32/gen.py -- do not edit.', '',
       'import "encoding";', '',
       'fn dec(r: result[bytes, str]) -> str {',
       '    guard let b = r else let e = err_of(r) { return "ERR " + e; }',
       '    return encoding.hex_encode(b);',
       '}', '']
exp = []
for b in inputs:
    std = base64.b32encode(b).decode()
    hx = base64.b32hexencode(b).decode()
    ck = crock_enc(b)
    if b:
        assert int.from_bytes(b, "big") << (-len(b) * 8 % 5) == int(ck.translate(str.maketrans(CROCK, "0123456789ABCDEFGHIJKLMNOPQRSTUV")), 32)
    src.append('println(encoding.base32_encode(%s));' % lit(b))
    src.append('println(encoding.base32hex_encode(%s));' % lit(b))
    src.append('println(encoding.crockford_encode(%s));' % lit(b))
    exp += [std, hx, ck]
    # decoding: canonical, lowercase, unpadded; Crockford with confusables and hyphens
    for s in (std, std.lower(), std.rstrip("=")):
        src.append('println(dec(encoding.base32_decode(%s)));' % slit(s))
        exp.append(b.hex())
    src.append('println(dec(encoding.base32hex_decode(%s)));' % slit(hx.lower().rstrip("=")))
    exp.append(b.hex())
    fuzzy = "-".join(ck[i:i + 4] for i in range(0, len(ck), 4)).replace("0", "o").replace("1", "l").lower()
    src.append('println(dec(encoding.crockford_decode(%s)));' % slit(fuzzy))
    exp.append(b.hex())

errors = [
    ("base32_decode", "MZXW6YQ", "a trailing group of characters that holds no whole byte"),  # 7 chars ok? no: see check
    ("base32_decode", "M", "a trailing group of characters that holds no whole byte"),
    ("base32_decode", "MZX", "a trailing group of characters that holds no whole byte"),
    ("base32_decode", "MZXW6Y", "a trailing group of characters that holds no whole byte"),
    ("base32_decode", "MY======", None),
    # Python accepts these two; their leftover bits are not zero
    ("base32_decode", "MZ======", "trailing bits that are not zero (a mistyped or truncated value)"),
    ("base32_decode", "MB======", "trailing bits that are not zero (a mistyped or truncated value)"),
    ("base32_decode", "MZXW6==", "padded input is not a multiple of 8 characters at offset 7"),
    ("base32_decode", "MZ1W6YTB", "byte not in the alphabet at offset 2"),
    ("base32_decode", "MZ-W6YTB", "byte not in the alphabet at offset 2"),
    ("base32hex_decode", "W0", "byte not in the alphabet at offset 0"),
    ("crockford_decode", "7U", "byte not in the alphabet at offset 1"),
]
for fn, s, want in errors:
    # what Python makes of it, as a cross-check of which inputs are bad
    try:
        py = base64.b32decode(s + "=" * (-len(s) % 8)) if fn == "base32_decode" else None
    except Exception:
        py = None
    if want is None:
        assert py is not None and base64.b32encode(py).decode() == s
        exp.append(py.hex())
    elif fn == "base32_decode" and "alphabet" not in want and "padded" not in want:
        if s == "MZXW6YQ":
            # 7 characters are 4 bytes: valid only with zero trailing bits
            assert py is not None
            exp.append(py.hex())
            src.append('println(dec(encoding.%s(%s)));' % (fn, slit(s)))
            continue
        exp.append("ERR %s: %s" % (fn, want))
    else:
        exp.append("ERR %s: %s" % (fn, want))
    src.append('println(dec(encoding.%s(%s)));' % (fn, slit(s)))

with open(os.path.join(HERE, "main.sl"), "w") as f:
    f.write("\n".join(src) + "\n")
with open(os.path.join(HERE, "expected.txt"), "w") as f:
    f.write("\n".join(exp) + "\n")
print(len(exp), "lines")
