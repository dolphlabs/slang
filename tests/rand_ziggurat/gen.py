#!/usr/bin/env python3
"""Writes stdlib/rand/ziggurat.sl: the 256-layer ziggurat tables for the
standard normal and the exponential(1) distributions (Marsaglia and Tsang
2000, the layout rand_distr uses). Plain double arithmetic, so the tables
are bit-identical to rand_distr's. Run from the repository root."""
from math import exp, log, sqrt

N = 256

def tables(r, v, f, f_inv):
    x = [0.0] * (N + 1)
    x[0] = v / f(r)
    x[1] = r
    for i in range(2, N):
        x[i] = f_inv(v / x[i - 1] + f(x[i - 1]))
    return x, [f(t) for t in x]

NORM_R, NORM_V = 3.6541528853610088, 0.00492867323399
EXP_R, EXP_V = 7.697117470131487, 0.0039496598225815571993
nx, nf = tables(NORM_R, NORM_V, lambda t: exp(-t * t / 2), lambda y: sqrt(-2 * log(y)))
ex, ef = tables(EXP_R, EXP_V, lambda t: exp(-t), lambda y: -log(y))

def fn(name, doc, vals):
    arms = "\n".join(f"        case {i} {{ {repr(float(v))} }}" for i, v in enumerate(vals))
    return f"""// {doc}
fn {name}(i: int) -> float {{
    return switch i {{
{arms}
        default {{ 0.0 }}
    }};
}}
"""

out = ["""// Generated by tests/rand_ziggurat/gen.py; do not edit.
//
// Ziggurat tables for normal() and exponential(): x[i] is the right edge
// of layer i (x[0] is the base layer's virtual width, x[256] is 0) and
// f[i] the unnormalised density there. A switch over constants compiles
// to a static lookup table, the only way to hold a constant array in a
// slang package without building it at startup.
"""]
out.append(f"let ZIG_NORM_R = {NORM_R!r};\nlet ZIG_EXP_R = {EXP_R!r};\n")
out.append(fn("zig_norm_x", "Normal layer edges.", nx))
out.append(fn("zig_norm_f", "exp(-x*x/2) at each normal edge.", nf))
out.append(fn("zig_exp_x", "Exponential layer edges.", ex))
out.append(fn("zig_exp_f", "exp(-x) at each exponential edge.", ef))
open("stdlib/rand/ziggurat.sl", "w").write("\n".join(out))
