"""Generates tests/crypto_oaep/{main.sl,expected.txt}.

Ciphertexts made by the openssl CLI (pkeyutl, OAEP over SHA-1 and SHA-256)
must decrypt to their messages; crypto's own encryption must decrypt back
(OAEP is randomised, so it cannot be compared byte for byte).

    python3 tests/crypto_oaep/gen.py
"""
import os
import subprocess
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
tmp = tempfile.mkdtemp()
key = os.path.join(tmp, "k.pem")
pub = os.path.join(tmp, "p.pem")
subprocess.run(["openssl", "genpkey", "-algorithm", "RSA", "-pkeyopt", "rsa_keygen_bits:2048", "-out", key], check=True,
               capture_output=True)
subprocess.run(["openssl", "pkey", "-in", key, "-pubout", "-out", pub], check=True, capture_output=True)
priv_pem = open(key).read()
pub_pem = open(pub).read()


def lit(b):
    return 'b"' + "".join("\\x%02x" % c for c in b) + '"'


def slit(s):
    return "to_str(" + lit(s.encode()) + ")"


msgs = [b"", b"secret password\x00", bytes(range(180))]
src = ['// Generated by tests/crypto_oaep/gen.py -- do not edit.', '', 'import "crypto";', 'import "encoding";', '',
       'let priv_key = %s;' % slit(priv_pem), 'let pub_key = %s;' % slit(pub_pem), '',
       'fn show(r: result[bytes, str]) {',
       '    guard let b = r else let e = err_of(r) { println("ERR " + e); return; }',
       '    println(encoding.hex_encode(b));',
       '}', '']
exp = []
for md in ("sha1", "sha256"):
    for m in msgs:
        mf = os.path.join(tmp, "m")
        open(mf, "wb").write(m)
        ct = subprocess.run(["openssl", "pkeyutl", "-encrypt", "-pubin", "-inkey", pub, "-in", mf,
                             "-pkeyopt", "rsa_padding_mode:oaep", "-pkeyopt", "rsa_oaep_md:" + md,
                             "-pkeyopt", "rsa_mgf1_md:" + md], check=True, capture_output=True).stdout
        src.append('show(crypto.rsa_decrypt_oaep_%s(priv_key, %s));' % (md, lit(ct)))
        exp.append(m.hex())
        src.append('show(crypto.rsa_decrypt_oaep_%s(priv_key, crypto.rsa_encrypt_oaep_%s(pub_key, %s) ?? b""));' % (md, md, lit(m)))
        exp.append(m.hex())
    # the wrong hash, a too-long message, a key of the wrong kind
    src.append('show(crypto.rsa_decrypt_oaep_%s(priv_key, crypto.rsa_encrypt_oaep_%s(pub_key, b"x") ?? b""));' %
               (md, "sha256" if md == "sha1" else "sha1"))
    exp.append("ERR rsa: decryption failed")
    src.append('show(crypto.rsa_encrypt_oaep_%s(pub_key, %s));' % (md, lit(bytes(300))))
    exp.append("ERR rsa: the message is too long for the key")
src.append('show(crypto.rsa_encrypt_oaep_sha1("not a key", b"x"));')
exp.append("ERR rsa: not an RSA public key in PEM form")
src.append('show(crypto.rsa_decrypt_oaep_sha1(pub_key, b"x"));')
exp.append("ERR rsa: not an RSA private key in PEM form")
src.append('println(len(crypto.rsa_encrypt_oaep_sha1(pub_key, b"x") ?? b"") == 256);')
exp.append("true")

with open(os.path.join(HERE, "main.sl"), "w") as f:
    f.write("\n".join(src) + "\n")
with open(os.path.join(HERE, "expected.txt"), "w") as f:
    f.write("\n".join(exp) + "\n")
print(len(exp), "lines")
