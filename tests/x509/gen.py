#!/usr/bin/env python3
"""Generates tests/x509/main.sl: a fixed chain made with the openssl CLI
(3.4 or later, for -not_before/-not_after), embedded as PEM literals.

    root (EC P-256, CA, pathlen 1)
      intermediate (EC P-384, CA, pathlen 0)
        leaf     RSA 2048, server_auth, every SAN type, serial 1234abcd
        old      expired in 2021
        client   Ed25519, client_auth
    other root   unrelated, for the unknown-issuer case

Signatures are randomized, so a re-run changes the fingerprints and the
expected output must be regenerated with it. Run from the repo root:
    python3 tests/x509/gen.py && slangc tests/x509/main.sl --run > tests/x509/expected.txt
"""
import pathlib
import subprocess
import tempfile

HERE = pathlib.Path(__file__).resolve().parent


def run(*args, cwd):
    subprocess.run(["openssl", *args], cwd=cwd, check=True,
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def main():
    with tempfile.TemporaryDirectory() as d:
        w = pathlib.Path(d)
        (w / "int.ext").write_text(
            "basicConstraints=critical,CA:TRUE,pathlen:0\n"
            "keyUsage=critical,keyCertSign,cRLSign\n"
            "subjectKeyIdentifier=hash\nauthorityKeyIdentifier=keyid\n")
        (w / "leaf.ext").write_text(
            "basicConstraints=critical,CA:FALSE\n"
            "keyUsage=critical,digitalSignature,keyEncipherment\n"
            "extendedKeyUsage=serverAuth\n"
            "subjectAltName=DNS:api.example.com,DNS:*.example.com,IP:127.0.0.1,"
            "IP:::1,email:ops@example.com,URI:https://example.com/id\n"
            "authorityKeyIdentifier=keyid\n")
        (w / "old.ext").write_text(
            "basicConstraints=critical,CA:FALSE\n"
            "extendedKeyUsage=serverAuth\n"
            "subjectAltName=DNS:old.example.com\n")
        (w / "client.ext").write_text(
            "basicConstraints=critical,CA:FALSE\n"
            "keyUsage=critical,digitalSignature\n"
            "extendedKeyUsage=clientAuth\n"
            "subjectAltName=URI:spiffe://example.com/client-7\n")

        span = ["-not_before", "20250101000000Z", "-not_after", "20450101000000Z"]
        run("ecparam", "-name", "prime256v1", "-genkey", "-noout", "-out", "root.key", cwd=w)
        run("req", "-x509", "-new", "-key", "root.key", "-subj", "/O=slang tests/CN=Test Root",
            "-set_serial", "1", *span, "-config", "/dev/null",
            "-addext", "basicConstraints=critical,CA:TRUE,pathlen:1",
            "-addext", "keyUsage=critical,keyCertSign,cRLSign",
            "-out", "root.pem", cwd=w)
        run("ecparam", "-name", "prime256v1", "-genkey", "-noout", "-out", "other.key", cwd=w)
        run("req", "-x509", "-new", "-key", "other.key", "-subj", "/CN=Other Root",
            "-set_serial", "9", *span, "-config", "/dev/null",
            "-addext", "basicConstraints=critical,CA:TRUE",
            "-addext", "keyUsage=critical,keyCertSign",
            "-out", "other.pem", cwd=w)

        def issue(name, keyargs, subj, serial, ca, ext, span_):
            run(*keyargs, cwd=w)
            run("req", "-new", "-key", name + ".key", "-subj", subj,
                "-config", "/dev/null", "-out", name + ".csr", cwd=w)
            run("x509", "-req", "-in", name + ".csr", "-CA", ca + ".pem", "-CAkey", ca + ".key",
                "-set_serial", serial, *span_, "-extfile", ext, "-out", name + ".pem", cwd=w)

        issue("int", ["ecparam", "-name", "secp384r1", "-genkey", "-noout", "-out", "int.key"],
              "/O=slang tests/CN=Test Intermediate", "2", "root", "int.ext", span)
        issue("leaf", ["genpkey", "-algorithm", "RSA", "-pkeyopt", "rsa_keygen_bits:2048",
                       "-out", "leaf.key"],
              "/C=NG/O=Example, Ltd./CN=api.example.com", "0x1234abcd", "int", "leaf.ext", span)
        issue("old", ["ecparam", "-name", "prime256v1", "-genkey", "-noout", "-out", "old.key"],
              "/CN=old.example.com", "3", "int", "old.ext",
              ["-not_before", "20200101000000Z", "-not_after", "20210101000000Z"])
        issue("client", ["genpkey", "-algorithm", "ED25519", "-out", "client.key"],
              "/CN=client-7", "4", "int", "client.ext", span)

        pems = {n: (w / (n + ".pem")).read_text() for n in
                ("root", "int", "leaf", "old", "client", "other")}

    def lit(s):
        return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'

    body = (HERE / "body.sl.in").read_text()
    head = "// Generated by tests/x509/gen.py from body.sl.in -- edit those, not this.\n\n"
    head += 'import "strings";\nimport "x509";\n\n'
    for n, p in pems.items():
        head += "fn pem_%s() -> str {\n    return %s;\n}\n\n" % (n, lit(p))
    (HERE / "main.sl").write_text(head + "\n" + body)


main()
