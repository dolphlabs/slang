#!/usr/bin/env python3
"""Writes runtime/sl_ryu_tables.c: the two power-of-5 tables Ryu needs
(runtime/sl_ryu.c), from Python's exact integers rather than by hand.

    python3 runtime/gen_ryu.py          # rewrite the tables
    python3 runtime/gen_ryu.py --check  # fail if they are out of date

POW5_INV_SPLIT[q] is ceil(2^(bitlen(5^q) - 1 + 125) / 5^q) -- the reciprocal
of 5^q scaled to 125 bits plus its leading bits -- for q in [0, 342), and
POW5_SPLIT[i] is 5^i scaled to exactly 125 bits (shifted down or up), for i
in [0, 326). Each is a 128-bit number stored as {low 64 bits, high 64
bits}. These are the tables of Ulf Adams' reference implementation
(github.com/ulfjack/ryu, d2s_full_table.h), computed the same way.
"""

import sys
from pathlib import Path

INV_BITCOUNT = 125
BITCOUNT = 125
INV_COUNT = 342
COUNT = 326
MASK64 = (1 << 64) - 1


def inv_split(q):
    p = 5 ** q
    j = p.bit_length() - 1 + INV_BITCOUNT
    return (1 << j) // p + 1


def split(i):
    p = 5 ** i
    shift = p.bit_length() - BITCOUNT
    return p >> shift if shift >= 0 else p << -shift


def row(v):
    assert v < (1 << 128)
    return "    {%duLL, %duLL}," % (v & MASK64, v >> 64)


def render():
    out = [
        "/* ---- Ryu's power-of-5 tables: generated by runtime/gen_ryu.py ----",
        " *",
        " * Do not edit; rerun the generator. Used by runtime/sl_ryu.c. */",
        "",
        "static const uint64_t SL_RYU_POW5_INV_SPLIT[%d][2] = {" % INV_COUNT,
    ]
    out += [row(inv_split(q)) for q in range(INV_COUNT)]
    out += ["};", "", "static const uint64_t SL_RYU_POW5_SPLIT[%d][2] = {" % COUNT]
    out += [row(split(i)) for i in range(COUNT)]
    out += ["};", ""]
    return "\n".join(out)


def main():
    target = Path(__file__).resolve().parent / "sl_ryu_tables.c"
    text = render()
    if "--check" in sys.argv:
        if not target.exists() or target.read_text() != text:
            sys.exit("runtime/sl_ryu_tables.c is out of date: run "
                     "python3 runtime/gen_ryu.py")
        return
    target.write_text(text)


if __name__ == "__main__":
    main()
